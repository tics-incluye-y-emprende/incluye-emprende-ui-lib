import type { ChangeEvent } from "react";
import { ValidationsConfig, ValidationsState } from "../validation/models";

/** Native elements a field can be bound to. */
export type FieldElement =
  | HTMLInputElement
  | HTMLTextAreaElement
  | HTMLSelectElement;

/** All the properties of the three elements combined, so props that exist only on some of them (e.g. `pattern`) can be picked. */
export type allFieldElementProps = HTMLInputElement &
  HTMLTextAreaElement &
  HTMLSelectElement;

/**
 * Unmodified value of a field. Multiple selects hold several strings. Undefined means no value.
 * This version does not handle groups of checkboxes that share a name.
 */
export type RawValue = string | string[] | undefined;

/**
 * Default value of a field, always raw (never a payload value).
 * This version supports a single string: a multiple select can have only one option selected by default.
 */
export type DefaultValue = string | undefined;

/** Configuration of one field, identified by the Payload key `K`. */
export interface FormControlConfig<Payload, K extends keyof Payload> {
  /**
   * Transforms the raw value into the typed value for this key (e.g. "3" into 3).
   * It also serves default, patched, set and reset values, which have no event.
   * The event of the change lets it choose other data of the element, such as
   * `e.target.checked` or `e.target.files`; it is undefined when there was no event.
   * Returns undefined when there is no usable value.
   */
  rawToPayloadAdapter: (
    rawValue: RawValue,
    e?: ChangeEvent<FieldElement>,
  ) => Payload[K] | undefined;
  /** Raw value the field starts with. */
  defaultValue?: DefaultValue;
  /**
   * Display-only: returns the text to show while the field is not focused (3001234567 -> 300 123 4567).
   * It is not called for empty values and it does not validate or filter.
   * Only for text-like inputs (text, tel, search, url, password) and textarea.
   */
  formatter?: (rawValue: string) => string;
  /**
   * Validation rules of the field, e.g. `{ required: { propValue: true } }`.
   * `required` is one more rule; without it, the other rules are still evaluated with empty values.
   * A field without value (undefined) does not pass them: see validation.md.
   */
  validations?: ValidationsConfig;
}

/** A value together with the one it is related to. */
export interface ValueSate<V = RawValue> {
  /** The value right now. */
  readonly currentValue: V;
  /** The earlier value; what "earlier" means depends on the field of formControlI. */
  readonly prevValue?: V;
  /** Whether the value is considered changed; the comparison depends on the field of formControlI. */
  readonly hasChanged: boolean;
}

/** Immutable state of one field: each operation returns a new control and only changes what its comment says. */
export interface formControlI<Payload, K extends keyof Payload> {
  /**
   * currentValue is the last default value. prevValue is the one it had before the last patch;
   * undefined until the first one.
   * hasChanged is false until the first patch; then, it is true when both are different.
   */
  readonly defaultValue: ValueSate<DefaultValue>;
  /**
   * Last value of the element without any modification, never formatted.
   * prevValue is the value before the last operation that changed the value; undefined at the beginning.
   * hasChanged is true when currentValue differs from defaultValue.currentValue, no matter whether
   * it was changed by the user or by setValue. Empty values (undefined, "" and []) are different,
   * so a field that was written and cleared has changed and patchValue respects it. Lists are compared by content, ignoring the order; the default "red" equals ["red"].
   */
  readonly rawValue: ValueSate;
  /**
   * The typed value returned by `rawToPayloadAdapter` for the current raw value; undefined while
   * the field is not valid (validationState.isValid). The form builds the complete Payload.
   */
  readonly payloadValue: Payload[K] | undefined;
  /**
   * Text generated by the formatter for the current raw value, also while the element is focused;
   * undefined if there is no formatter or the value is empty or a list.
   */
  readonly formattedValue: string | undefined;
  /** True between the focus and blur events, when the element shows the raw value instead of the formatted one. */
  readonly isFocused: boolean;
  /** True once the element has been clicked or blurred (so keyboard users count), even if its value did not change; false again after reset. */
  readonly isTouched: boolean;
  /**
   * True while an asynchronous event of the field is being executed.
   * Any event can be asynchronous, depending on the consumer's implementation.
   * PENDING: how the control knows that one starts and ends; nothing sets it yet.
   */
  readonly isLoading?: boolean;
  /** Result of running the field's validations over the raw value. */
  readonly validationState: ValidationsState;

  /** Reads the new raw value from the event's element and passes it to the adapter, with the event. Throws if the element is not supported. */
  change(e: ChangeEvent<FieldElement>): formControlI<Payload, K>;
  /** Marks the field as focused. */
  focus(): formControlI<Payload, K>;
  /** Marks the field as touched and no longer focused. */
  blur(): formControlI<Payload, K>;
  /** Marks the field as touched. */
  click(): formControlI<Payload, K>;
  /**
   * Replaces the current default value, keeping the last one as defaultValue.prevValue.
   * undefined removes the default value.
   * It also updates rawValue, payloadValue and formattedValue, but only if the field
   * has not changed (rawValue.hasChanged is false).
   */
  patchValue(value: DefaultValue): formControlI<Payload, K>;
  /** Updates rawValue, payloadValue and formattedValue, but never defaultValue. */
  setValue(value: RawValue): formControlI<Payload, K>;
  /**
   * Returns rawValue to the current default value, updating payloadValue and formattedValue, so
   * rawValue.hasChanged is false. The field is no longer touched, so its errors are not shown
   * immediately; isFocused does not change.
   */
  reset(): formControlI<Payload, K>;
}
