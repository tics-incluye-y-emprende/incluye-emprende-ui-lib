/**
 * Knows how to show a value in one kind of native element and how to read the state that validations need.
 * Reading the payload value is the eventToPayloadAdapter's responsibility.
 */
export abstract class FormControlStrategy<
  Element extends FieldElement = FieldElement,
> {
  constructor(protected readonly element: Element) {}

  /** Shows a value in the element: its text, its option or whether it is checked. Writes only what differs. */
  abstract setElementValue(value: ElementValue): void;

  /** Reads the properties that validations need. Every property is defined. */
  abstract getElementState(): ElementState;
}

