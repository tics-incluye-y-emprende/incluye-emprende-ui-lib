/** Temporary placeholder state, to be removed with the implementation. */
const mockedState: ValueSate = {
  currentValue: "",
  prevValue: "",
  hasChanged: false,
};

/** Temporary placeholder state, to be removed with the implementation. */
const mockedDefaultState: ValueSate<DefaultValue> = {
  currentValue: "",
  prevValue: "",
  hasChanged: false,
};

/** Immutable state of one field. It exists before any element is known. */
export class FormControl<Payload, K extends keyof Payload>
  implements formControlI<Payload, K>
{
  /** Evaluates the raw value against the configured rules. */
  protected readonly validator: ValidatorI;

  /** The validator can be injected, mainly for tests; by default it is built from `config.validations`. */
  constructor(
    protected readonly config: FormControlConfig<Payload, K>,
    validator?: ValidatorI,
  ) {
    this.validator =
      validator ?? new Validator({ validations: config.validations ?? {} });
  }

  /** Result of validating the current raw value. */
  public get validationState(): ValidationsState {
    return this.validator.validate(this.rawValue.currentValue);
  }

  /** Current default value and the first one. */
  public get defaultValue(): ValueSate<DefaultValue> {
    return mockedDefaultState;
  }

  /** Last value of the element, unmodified. */
  public get rawValue(): ValueSate {
    return mockedState;
  }

  /** Value converted to its Payload type by the adapter; undefined until there is one. */
  public get payloadValue(): ValueSate<Payload[K] | undefined> {
    return {
      currentValue: undefined,
      prevValue: undefined,
      hasChanged: false,
    };
  }

  /** Last text generated by the formatter, if any. */
  public get formattedValue(): string | undefined {
    return undefined;
  }

  /** Whether the element is focused. */
  public get isFocused(): boolean {
    return false;
  }

  /** Whether the field has been blurred. */
  public get isTouched(): boolean {
    return false;
  }

  /** Uses executeFormControlStrategy to read the element of the event. */
  public change(_e: ChangeEvent<FieldElement>): FormControl<Payload, K> {
    throw new Error("Not implemented");
  }

  /** Returns a focused control. */
  public focus(): FormControl<Payload, K> {
    throw new Error("Not implemented");
  }

  /** Returns a touched control without focus. */
  public blur(): FormControl<Payload, K> {
    throw new Error("Not implemented");
  }

  /** Returns a control with another default value and, if the user has not changed it, another current value. */
  public patchValue(_value: DefaultValue): FormControl<Payload, K> {
    throw new Error("Not implemented");
  }

  /** Returns a control with another current value and the same default value. */
  public setValue(_value: RawValue): FormControl<Payload, K> {
    throw new Error("Not implemented");
  }
}

/** Knows how to read and show the raw value in one kind of native element. */
export abstract class FormControlStrategy<
  Element extends FieldElement = FieldElement,
> {
  constructor(protected readonly element: Element) {}

  /** Returns the next raw value. The current one is needed for checkbox groups, where each event concerns a single box. */
  abstract getRawValue(currentValue: RawValue): RawValue;

  /** Shows a raw value in the element: its text, checked state or selected options. Writes only what differs. */
  abstract setRawValue(rawValue: RawValue): void;
}

